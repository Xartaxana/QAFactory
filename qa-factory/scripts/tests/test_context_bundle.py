def sections(text: str) -> dict:
    """The view split by its `## ` headings: {name: [lines]} (the name is the heading's first word)."""
    found, name = {}, None
    for line in text.splitlines():
        if line.startswith("## "):
            name = line[3:].split(" ")[0]
            found[name] = []
        elif name is not None:
            found[name].append(line)
    return found


def cells(line: str) -> list:
    """The inverse of the view's escaping: split a line on its unescaped ` | ` and unescape each cell."""
    out, cur, i = [], [], 0
    while i < len(line):
        if line[i] == "\\" and i + 1 < len(line):
            cur.append({"n": "\n", "|": "|", "\\": "\\"}.get(line[i + 1], "\\" + line[i + 1]))
            i += 2
        elif line.startswith(" | ", i):
            out.append("".join(cur))
            cur, i = [], i + 3
        else:
            cur.append(line[i])
            i += 1
    out.append("".join(cur))
    return out


def project_at(base: Path, name: str, marker: bool = True) -> Path:
    """A folder under `base`, resolved (the bundle resolves --root; an 8.3 temp name would not match), with the project
    marker `qa-factory/config.json` when asked."""
    root = base / name
    root.mkdir(parents=True, exist_ok=True)
    root = root.resolve()
    if marker:
        (root / "qa-factory").mkdir(exist_ok=True)
        (root / "qa-factory" / "config.json").write_text("{}", encoding="utf-8")
    return root


