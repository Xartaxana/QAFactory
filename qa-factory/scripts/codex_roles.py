"""Export canonical roles to native project-scoped Codex TOML agents."""
import argparse
import json
from pathlib import Path
from hooklib import PLUGIN_ROOT, parse_frontmatter
from hooklib import sorted_paths

MARKER = '# Generated by qa-factory codex_roles.py; canonical source: agents/*.md\n'


def definitions(policy=None):
    policy = policy or {}
    result = {}
    for source in sorted_paths((PLUGIN_ROOT / 'agents').glob('*.md')):
        text = source.read_text(encoding='utf-8')
        meta = parse_frontmatter(text)
        body = text.split('---', 2)[-1].strip()
        role = meta.get('name') or source.stem
        fields = {'name': role, 'description': meta.get('description') or role,
                  'developer_instructions': body}
        override = policy.get('roles', {}).get(role, {})
        for key, target in (('model','model'), ('effort','model_reasoning_effort')):
            if override.get(key) not in (None, 'inherit'):
                fields[target] = override[key]
        result[source.stem+'.toml'] = MARKER + '\n'.join(k+' = '+json.dumps(v,ensure_ascii=False) for k,v in fields.items())+'\n'
    return result


def export(root, policy=None, write=False):
    destination = Path(root).resolve() / '.codex/agents'
    files = definitions(policy)
    for name, text in files.items():
        path = destination / name
        if path.exists() and not path.read_text(encoding='utf-8').startswith(MARKER):
            raise ValueError('Refusing to overwrite a user-owned agent: '+str(path))
    if write:
        destination.mkdir(parents=True,exist_ok=True)
        for name, text in files.items():
            (destination / name).write_text(text,encoding='utf-8')
    return {'status':'written' if write else 'preview','directory':str(destination),'roles':list(files),
            'next':'Review native hooks and start a fresh Codex session. Exporting roles does not enable or trust hooks.'}


def check_override(root, role, desired):
    """CLI spawn uses the native agent profile, not unsupported model arguments."""
    import re
    path = Path(root) / '.codex/agents' / (role+'.toml')
    if not path.exists():
        raise ValueError('Native Codex role missing; export roles with codex_roles.py --root <project> --write and reload the host')
    text = path.read_text(encoding='utf-8')
    profile = {}
    for key in ('model','model_reasoning_effort'):
        match = re.search(r'^'+key+r'\s*=\s*("(?:[^"\\]|\\.)*"|\'[^\']*\')\s*$', text, re.M)
        if match:
            value = match.group(1)
            profile[key] = json.loads(value) if value.startswith('"') else value[1:-1]
    for key, target in (('model','model'),('effort','model_reasoning_effort')):
        value=desired.get(key)
        actual=profile.get(target, 'inherit')
        if value not in (None,'inherit') and actual != value:
            raise ValueError(f'Native {role} {key} mismatch: controller={value}, profile={actual}; update the explicit role policy and reload before dispatch')


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', required=True)
    parser.add_argument('--policy', help='JSON role model/effort overrides; omitted fields inherit the host')
    parser.add_argument('--write', action='store_true')
    args=parser.parse_args()
    policy=json.loads(Path(args.policy).read_text(encoding='utf-8')) if args.policy else {}
    print(json.dumps(export(args.root,policy,args.write),indent=2))
